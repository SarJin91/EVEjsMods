const NO_TARGET_REASONS = Object.freeze({
  NO_ANCHOR: "no anchor (station/base) to compute the range from",
  NO_CANDIDATE: "no candidates in range",
});

function describeNote(note) {
  const raw = typeof note === "string" ? note : String(note === undefined || note === null ? "" : note);
  const at = raw.indexOf(":");
  const code = at < 0 ? raw : raw.slice(0, at);
  let arg = at < 0 ? null : raw.slice(at + 1);
  if (arg === "") arg = null;
  const entry = Object.prototype.hasOwnProperty.call(NOTE_DICTIONARY, code) ? NOTE_DICTIONARY[code] : null;
  if (!entry) return { code, arg, category: "informacja", text: `Unknown note ${code}`, known: false };
  if (code === "NO_TARGET" && arg !== null && Object.prototype.hasOwnProperty.call(NO_TARGET_REASONS, arg)) {
    arg = NO_TARGET_REASONS[arg];
  }
  return { code, arg, category: entry.category, text: entry.text, known: true };
}

